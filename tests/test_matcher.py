@pytest.mark.parametrize(("message", "expected_sku"), MATCHED_CASES)
def test_matched_cases(
    matcher: ProductMatcher,
    message: str,
    expected_sku: str,
) -> None:
    result = matcher.match(message)

    assert result.status == "matched"
    assert len(result.candidates) == 1
    assert result.candidates[0].sku == expected_sku


@pytest.mark.parametrize(("message", "expected_prefix", "required"), AMBIGUOUS_CASES)
def test_ambiguous_cases(
    matcher: ProductMatcher,
    message: str,
    expected_prefix: str | None,
    required: set[str] | None,
) -> None:
    result = matcher.match(message)
    skus = {candidate.sku for candidate in result.candidates}

    assert result.status == "ambiguous"
    assert 2 <= len(result.candidates) <= 3
    if expected_prefix:
        assert all(sku.startswith(expected_prefix) for sku in skus)
    if required:
        assert required.issubset(skus)


@pytest.mark.parametrize("message", NOT_FOUND_CASES)
def test_not_found_cases(matcher: ProductMatcher, message: str) -> None:
    result = matcher.match(message)

    assert result.status == "not_found"
    assert result.candidates == []


def test_every_exact_catalog_name_returns_own_sku(
    matcher: ProductMatcher,
) -> None:
    for item in matcher.catalog.items:
        result = matcher.match(item.name)

        assert result.status == "matched", item.name
        assert len(result.candidates) == 1, item.name
        assert result.candidates[0].sku == item.sku, item.name


def test_duplicate_exact_names_are_ambiguous(tmp_path: Path) -> None:
    catalog_path = tmp_path / "catalog.csv"
    catalog_path.write_text(
        "sku,name,unit,price\n"
        "SKU-1,Одинаковый товар,шт,10\n"
        "SKU-2,Одинаковый товар,шт,20\n",
        encoding="utf-8",
    )
    matcher = ProductMatcher(Catalog.from_csv(catalog_path))

    result = matcher.match("Одинаковый товар")

    assert result.status == "ambiguous"
    assert {candidate.sku for candidate in result.candidates} == {"SKU-1", "SKU-2"}
